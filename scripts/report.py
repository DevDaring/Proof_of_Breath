"""Writes docs/evaluation-results.md and PNG charts from an evaluation export."""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
GENUINE, ATTACK = "#2a78d6", "#eb6834"


def pct(v) -> str:
    return "–" if v is None else f"{v * 100:.1f}%"


def num(v, digits=3) -> str:
    return "–" if v is None else f"{v:.{digits}f}"


def table(res: dict) -> list[str]:
    lines = ["| Condition | Metric | Rate | 95% CI | k / n | Median margin |", "| --- | --- | --- | --- | --- | --- |"]
    for c in res["conditions"]:
        ci = f"{pct(c['ci_low'])} to {pct(c['ci_high'])}" if c["n"] else "–"
        lines.append(f"| {c['label']} | {c['metric']} | {pct(c['rate'])} | {ci} | {c['k']} / {c['n']} | {num(c['s_decoy_median'], 2)} |")
    return lines


def section(res: dict, title: str) -> list[str]:
    if not res["n_trials"]:
        return [f"## {title}", "", "No trials."]
    t = res["time_to_approve"]
    return [
        f"## {title}", "", f"**{res['label']}** n = {res['n_trials']} trials, {res['n_participants']} participant code(s).", "",
        f"- False accept rate: {pct(res['far']['rate'])} (95% CI {pct(res['far']['ci_low'])} to {pct(res['far']['ci_high'])}, {res['far']['k']}/{res['far']['n']})",
        f"- False reject rate: {pct(res['frr']['rate'])} (95% CI {pct(res['frr']['ci_low'])} to {pct(res['frr']['ci_high'])}, {res['frr']['k']}/{res['frr']['n']})",
        f"- Time to approve: median {num(t['median_s'], 1)} s, p90 {num(t['p90_s'], 1)} s. {t['note']}.",
        "- AUC: " + ", ".join(f"{k} {num(v)}" for k, v in res["auc"].items()), "", *table(res),
    ]


def charts(res: dict, prefix: str, out: Path) -> list[str]:
    if not res["n_trials"]:
        return []
    out.mkdir(parents=True, exist_ok=True)
    hist = res["s_decoy_histogram"]
    x = [h["bin"] for h in hist]
    width = (x[1] - x[0]) * 0.42
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.bar([v - width / 2 for v in x], [h["genuine"] for h in hist], width, color=GENUINE, label="Genuine")
    ax.bar([v + width / 2 for v in x], [h["attack"] for h in hist], width, color=ATTACK, label="Attack or not following")
    ax.axvline(0, color="#555", linestyle="--", linewidth=1)
    ax.set_xlabel("S_decoy (margin over the best of 20 decoys)")
    ax.set_ylabel("Trials")
    ax.set_title(f"S_decoy by trial type: {res['data_class']} data")
    ax.legend(frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    a = out / f"{prefix}-s-decoy.png"
    fig.savefig(a, dpi=150)
    plt.close(fig)
    made = [a]
    if res["roc"]:
        fig, ax = plt.subplots(figsize=(4.5, 4.5))
        ax.step([p["fpr"] for p in res["roc"]], [p["tpr"] for p in res["roc"]], where="post", color=GENUINE, linewidth=2)
        ax.set_xlabel("False accept rate")
        ax.set_ylabel("True accept rate")
        ax.set_title(f"ROC, S_decoy: {res['data_class']} data")
        ax.spines[["top", "right"]].set_visible(False)
        fig.tight_layout()
        b = out / f"{prefix}-roc.png"
        fig.savefig(b, dpi=150)
        plt.close(fig)
        made.append(b)
    return [str(p.relative_to(ROOT / "docs")) for p in made]


def write(live: dict, simulated: dict, thresholds_note: str, path: Path = ROOT / "docs" / "evaluation-results.md") -> Path:
    charts_dir = ROOT / "docs" / "charts"
    lines = ["# Evaluation results", "", "Generated by `scripts/export_results.py` or `scripts/run_eval.py`. Do not edit by hand.", "", thresholds_note, ""]
    if live["n_trials"]:
        lines += section(live, "Live trials") + [""] + [f"![chart]({c})" for c in charts(live, "live", charts_dir)] + [""]
        lines += ["Limits: small n, a single webcam, limited lighting conditions. This measures attention, not identity.", ""]
    else:
        lines += ["## Live trials", "", "**None yet.** No result on this page describes a person. Live numbers appear here after the protocol in `evaluation-protocol.md` has been run with a real webcam.", ""]
    lines += section(simulated, "Simulated signals (a check of the verifier, not a measurement of people)") + [""]
    lines += [f"![chart]({c})" for c in charts(simulated, "simulated", charts_dir)] + [""]
    lines += ["Simulated signals are generated by `backend/app/core/simulate.py`. They are far cleaner than a webcam will be, so these rates are an upper bound on how the verifier could behave. They must not be reported as real-world performance."]
    path.write_text("\n".join(lines) + "\n")
    return path
